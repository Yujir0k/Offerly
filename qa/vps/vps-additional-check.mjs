import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {call,state,act,catalog,save,check,checks,calls,base,dir,fixture} from './vps-client.mjs';
const users=JSON.parse(await readFile(dir+'/users.json','utf8'));
const {e,e2,c,c2,flow}=users;
for(const u of [e,e2,c,c2])await state(u);
const hiring=(u,type,b={},status=200)=>call(u,'/api/hiring',{type,...b},status);
let thread=await call(c,'/api/conversations/'+flow.room);
let expired=thread.messages.find(m=>m.id===flow.timedTask).task;
while(expired.status==='accepted'){
 await new Promise(resolve=>setTimeout(resolve,Math.min(10000,Math.max(100,Date.parse(expired.deadlineAt)-Date.now()+100))));
 expired=(await call(c,'/api/conversations/'+flow.room)).messages.find(m=>m.id===flow.timedTask).task;
}
check('real one-minute deadline expires',expired.status==='expired'&&expired.answer==='Частичный ответ, успешно сохранённый до срока.');
check('expired candidate conditions inaccessible',!expired.instructions&&!expired.criteria);
for(const b of [{type:'task-response',status:'submitted',answer:'Поздний ответ'},{type:'task-draft',revision:999,answer:'Поздний черновик'},{type:'task-response',status:'accepted'}])await call(c,'/api/conversations/'+flow.room,{...b,messageId:flow.timedTask},409);
check('partial answer available to employer',(await call(e,'/api/conversations/'+flow.room)).messages.find(m=>m.id===flow.timedTask).task.answer===expired.answer);
const beforeNotifications=(await state(c)).notificationItems;
await call(c,'/api/conversations/'+flow.room);
check('timeout does not duplicate notifications',JSON.stringify((await state(c)).notificationItems)===JSON.stringify(beforeNotifications));
await call(e,'/api/conversations/'+flow.room,{type:'task-review',messageId:flow.timedTask,feedback:'Частичный результат рассмотрен.'});
check('expired result can be reviewed',(await call(c,'/api/conversations/'+flow.room)).messages.find(m=>m.id===flow.timedTask).task.feedback.includes('рассмотрен'));
let cat=await catalog(e,'candidates',{sort:'По результату теста'});
const ids=cat.items.slice(0,7).map(p=>p.id);
check('compare seven without a three-person limit',(await hiring(e,'compare',{ids})).items.length===7);
check('compare respects hidden contacts',(await hiring(e2,'compare',{ids})).items.every(p=>!p.email&&!p.phone));
await hiring(e,'compare',{ids:[ids[0]]},400);await hiring(c,'compare',{ids},403);
const search=await hiring(e,'search-save',{name:'VPS QA saved search',filters:{query:String(c.state.profile.id)}});
check('saved search matches tested candidate',(await hiring(e,'search-matches',{id:search.id})).items.some(p=>p.id===c.state.profile.id));
await hiring(e2,'search-delete',{id:search.id},404);
await hiring(e,'search-seen',{id:search.id});check('seen search has no new matches',(await hiring(e,'search-matches',{id:search.id})).newIds.length===0);
await hiring(e,'search-update',{id:search.id,enabled:false});await hiring(e,'search-delete',{id:search.id});
await act(c2,'apply',{id:flow.job,shareContacts:false,message:'Интересна вакансия'},400);
await act(c2,'apply',{id:flow.job,shareContacts:true,message:'Готов обсудить работу.'});
const application=c2.state.applications.find(a=>a.jobId===flow.job);
const appliedRoom=await call(c2,'/api/conversations',{applicationId:application.id});
check('application opens same chat for both roles',(await call(e,'/api/conversations',{applicationId:application.id})).id===appliedRoom.id);
await act(e2,'application-status',{id:application.id,jobId:flow.job,status:'Просмотрен'},400);
await act(e,'application-status',{id:application.id,jobId:flow.job,status:'Просмотрен'});
check('application status visible to candidate',(await state(c2)).applications.find(a=>a.id===application.id).status==='Просмотрен');
await hiring(c,'block',{companyId:e2.state.company.id,blocked:true});
check('blocked company cannot find candidate',!(await catalog(e2,'candidates',{query:String(c.state.profile.id)})).items.some(p=>p.id===c.state.profile.id));
await hiring(c,'block',{companyId:e2.state.company.id,blocked:false});
check('unblock restores visibility',(await catalog(e2,'candidates',{query:String(c.state.profile.id)})).items.some(p=>p.id===c.state.profile.id));
const invitation={candidateId:c2.state.profile.id,title:'QA invitation management',description:'Тест изменения и отмены',min:150000,max:200000,contact:e2.email,format:'Удалённо',grade:'Junior',skills:['Python']};
await act(e2,'invite',invitation);let inv=e2.state.invitations.find(i=>i.candidateId===c2.state.profile.id);const oldRevision=inv.updatedAt||inv.createdAt;
await act(e2,'invitation-update',{...invitation,id:inv.id,expectedUpdatedAt:oldRevision,description:'Обновлённое предложение'});inv=e2.state.invitations.find(i=>i.id===inv.id);
await act(c2,'respond',{id:inv.id,status:'accepted',expectedUpdatedAt:oldRevision},400);
await act(e2,'invitation-cancel',{id:inv.id,expectedUpdatedAt:inv.updatedAt});
check('cancelled invitation visible',(await state(c2)).invitations.find(i=>i.id===inv.id).status==='cancelled');
await act(c2,'respond',{id:inv.id,status:'accepted',expectedUpdatedAt:inv.updatedAt},400);
await act(e2,'invite',invitation);inv=e2.state.invitations.find(i=>i.candidateId===c2.state.profile.id&&i.status==='sent');
await act(c2,'respond',{id:inv.id,status:'declined',expectedUpdatedAt:inv.updatedAt||inv.createdAt,declineReason:'Не подходят условия'});
check('invitation refusal persists',(await state(e2)).invitations.find(i=>i.id===inv.id).status==='declined');
for(const u of [e,c])await call(u,'/api/drafts?key=settings:tour_preferences_v1',{value:{disabled:true}},200,{method:'PUT'});
await save('users.json',users);
check('non-QA rows preserved',JSON.stringify(fixture({action:'baseline'}))===JSON.stringify(JSON.parse(await readFile(dir+'/baseline-before.json','utf8'))));
await save('additional.json',{at:new Date().toISOString(),calls,checks:checks.length,passed:checks});
