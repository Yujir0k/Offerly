CREATE TABLE IF NOT EXISTS users (
 id text PRIMARY KEY, email text NOT NULL UNIQUE, password_hash text, name text NOT NULL,
 scope text NOT NULL DEFAULT 'public', demo boolean NOT NULL DEFAULT false,
 verified_at timestamptz, deleted_at timestamptz, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at timestamptz NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE TABLE IF NOT EXISTS account_state (
 user_id text PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 version integer NOT NULL DEFAULT 0, payload jsonb NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS candidate_profiles (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id text NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
 specialty text NOT NULL DEFAULT '', grade text, visible boolean NOT NULL DEFAULT false,
 consent boolean NOT NULL DEFAULT false, payload jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS profiles_category ON candidate_profiles(specialty,grade) WHERE visible AND consent;
CREATE TABLE IF NOT EXISTS companies (
 id text PRIMARY KEY, owner_id text NOT NULL REFERENCES users(id), scope text NOT NULL,
 payload jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS company_memberships (
 company_id text NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 role text NOT NULL CHECK(role IN ('owner','recruiter','viewer')),
 PRIMARY KEY(company_id,user_id)
);
CREATE TABLE IF NOT EXISTS needs (
 id text PRIMARY KEY, company_id text NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
 payload jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS jobs (
 id text PRIMARY KEY, company_id text NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
 status text NOT NULL CHECK(status IN ('draft','published','archived')),
 specialty text NOT NULL, grade text NOT NULL, min_salary integer NOT NULL DEFAULT 0,
 max_salary integer NOT NULL DEFAULT 0, payload jsonb NOT NULL,
 CHECK(min_salary >= 0 AND max_salary >= min_salary),
 CHECK(status <> 'published' OR min_salary > 0)
);
CREATE INDEX IF NOT EXISTS jobs_catalog ON jobs(status,specialty,grade);
CREATE TABLE IF NOT EXISTS invitations (
 id text PRIMARY KEY, company_id text NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
 candidate_id integer NOT NULL REFERENCES candidate_profiles(id) ON DELETE CASCADE,
 status text NOT NULL CHECK(status IN ('sent','viewed','accepted','declined')),
 min_salary integer NOT NULL, max_salary integer NOT NULL, payload jsonb NOT NULL,
 CHECK(min_salary > 0 AND max_salary >= min_salary)
);
CREATE UNIQUE INDEX IF NOT EXISTS active_invitation ON invitations(company_id,candidate_id) WHERE status IN ('sent','viewed');
CREATE INDEX IF NOT EXISTS invitations_candidate ON invitations(candidate_id,status);
CREATE TABLE IF NOT EXISTS applications (
 id text PRIMARY KEY, job_id text NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
 candidate_id integer NOT NULL REFERENCES candidate_profiles(id) ON DELETE CASCADE,
 status text NOT NULL, payload jsonb NOT NULL, UNIQUE(job_id,candidate_id)
);
CREATE INDEX IF NOT EXISTS applications_candidate ON applications(candidate_id);
CREATE TABLE IF NOT EXISTS surveys (
 id text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE, payload jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS assessments (
 id text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE, payload jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS saved_candidates (
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 candidate_id integer NOT NULL REFERENCES candidate_profiles(id) ON DELETE CASCADE,
 PRIMARY KEY(user_id,candidate_id)
);
CREATE TABLE IF NOT EXISTS favorite_jobs (
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 job_id text NOT NULL REFERENCES jobs(id) ON DELETE CASCADE, PRIMARY KEY(user_id,job_id)
);
CREATE TABLE IF NOT EXISTS drafts (
 id text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 payload jsonb NOT NULL, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS email_challenges (
 id text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 email text NOT NULL, code_hash text NOT NULL, expires_at timestamptz NOT NULL,
 attempts integer NOT NULL DEFAULT 0, used_at timestamptz, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS auth_throttles (
 key text PRIMARY KEY, count integer NOT NULL DEFAULT 0, reset_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS external_identities (
 issuer text NOT NULL, subject text NOT NULL, user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 participant_id text, PRIMARY KEY(issuer,subject)
);
