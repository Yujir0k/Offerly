export function normalizeSuggestion(value: string) {
  return value
    .trim()
    .toLocaleLowerCase("ru")
    .replace(/ё/g, "е")
    .replace(/[\s._-]+/g, " ");
}
export function matchingSuggestions(
  catalog: Suggestion[],
  query: string,
  limit = 12,
) {
  const term = normalizeSuggestion(query);
  return catalog
    .map((item, index) => {
      const terms = [item.name, ...(item.aliases || [])].map(
        normalizeSuggestion,
      );
      const score = !term
        ? 3
        : terms.some((text) => text === term)
          ? 0
          : terms.some((text) => text.startsWith(term))
            ? 1
            : terms.some((text) => text.includes(term))
              ? 2
              : 99;
      return { item, score, index };
    })
    .filter((item) => item.score < 99)
    .sort((a, b) => a.score - b.score || a.index - b.index)
    .slice(0, limit)
    .map((item) => item.item);
}
export function canonicalSuggestion(catalog: Suggestion[], input: string) {
  const key = normalizeSuggestion(input);
  return (
    catalog.find((item) =>
      [item.name, ...(item.aliases || [])].some(
        (name) => normalizeSuggestion(name) === key,
      ),
    )?.name || input.trim().slice(0, 100)
  );
}
