function dedupeSuggestions(items: Suggestion[]) {
  const seen = new Set<string>();
  return items.filter((item) => {
    const key = normalizeSuggestion(item.name);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}
