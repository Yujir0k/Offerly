export const demoVacancies: Job[] = listings.map(
  ({ employer, day, ...job }) => {
    const company = demoEmployers[employer];
    return {
      ...job,
      employment: job.employment || "Полная занятость",
      industry: company.industry,
      company: company.name,
      companyId: employer,
      logo: company.logo,
      companyDescription: company.description,
      companySize: company.size,
      publishedAt: `2026-10-${String(day).padStart(2, "0")}T09:00:00+03:00`,
      demo: true,
    };
  },
);

export function enrichVacancies(existing: Job[] = []): Job[] {
  const seeds = new Map(demoVacancies.map((job) => [job.id, job]));
  const rows = existing.map((job) => {
    const seed = seeds.get(job.id);
    // Only the two legacy seed listings need their initial placeholder copy upgraded.
    if (seed && !job.publishedAt) return { ...job, ...seed };
    return {
      industry: seed?.industry || "",
      city: "",
      employment: "Полная занятость",
      experienceMin: 0,
      employerOwned: !seed && !job.demo,
      ...job,
    };
  });
  const present = new Set(rows.map((job) => job.id));
  return [...rows, ...demoVacancies.filter((job) => !present.has(job.id))];
}
